//! # 编辑器模块（Core 层）
//!
//! 本模块包含编辑器相关的功能，当前主要提供自动纠错功能。
//!
//! ## 子模块
//!
//! - `autocorrect`: 自动纠错引擎，基于 Aho-Corasick 算法实现高效文本替换匹配
//!
//! ## 功能说明
//!
//! 编辑器模块为写作应用提供文本处理功能，包括：
//! 1. 自动纠错：检测并纠正常见的拼写错误
//! 2. 文本替换：支持批量文本替换操作
//! 3. 格式化：提供文本格式化功能
//!
//! ## 依赖关系
//!
//! - 依赖 `autocorrect` 子模块提供具体的纠错功能
//!
//! ## 使用场景
//!
//! - 写作时的实时拼写检查
//! - 批量文本替换和格式化
//! - 提高写作效率和质量

pub mod autocorrect;
